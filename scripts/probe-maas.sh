#!/usr/bin/env bash
# Mint a MaaS API key with the current oc token and probe Granite.
set -euo pipefail

command -v oc >/dev/null || { echo "oc is required" >&2; exit 1; }
command -v python3 >/dev/null || { echo "python3 is required" >&2; exit 1; }
command -v curl >/dev/null || { echo "curl is required" >&2; exit 1; }
oc whoami >/dev/null || { echo "Not logged in. Run oc login first." >&2; exit 1; }

MODEL="${MODEL:-granite-3-1-2b-instruct}"
SUBSCRIPTION="${SUBSCRIPTION:-free-models-subscription}"
PROMPT="${PROMPT:-Reply with a single word: pong}"
MAX_TOKENS="${MAX_TOKENS:-16}"
KEY_NAME="${KEY_NAME:-opentlc-lab-probe}"

HOST="${HOST:-}"
if [[ -z "${HOST}" ]]; then
  domain="$(oc get ingresses.config.openshift.io cluster -o jsonpath='{.spec.domain}' 2>/dev/null || true)"
  HOST="maas.${domain}"
fi

json_field() {
  python3 -c 'import json,sys
obj=json.load(sys.stdin)
for key in sys.argv[1:]:
    if not isinstance(obj, dict):
        obj=""
        break
    obj=obj.get(key, "")
if obj is None:
    obj=""
print(obj if not isinstance(obj, (dict, list)) else json.dumps(obj))' "$@"
}

CURL_OPTS=(-skS --http1.1 --connect-timeout 20 --max-time 120)

http_code() {
  local url="$1"
  shift
  curl -skS --http1.1 --connect-timeout 8 --max-time 15 -o /dev/null -w "%{http_code}" "$@" "${url}" 2>/dev/null || echo "000"
}

select_base_url() {
  local code addr
  echo "  probing https://${HOST}/" >&2
  code="$(http_code "https://${HOST}/")"
  if [[ "${code}" != "000" ]]; then
    echo "  using https://${HOST} (HTTP ${code})" >&2
    echo "https://${HOST}"
    return
  fi
  echo "  https://${HOST} timed out" >&2
  echo "  probing http://${HOST}/" >&2
  code="$(http_code "http://${HOST}/")"
  if [[ "${code}" != "000" && "${code}" != "301" && "${code}" != "302" && "${code}" != "307" && "${code}" != "308" ]]; then
    echo "  using http://${HOST} (HTTP ${code})" >&2
    echo "http://${HOST}"
    return
  fi
  addr="$(oc get gateway maas-default-gateway -n openshift-ingress -o jsonpath='{.status.addresses[0].value}' 2>/dev/null || true)"
  if [[ -n "${addr}" ]]; then
    echo "  probing http://${addr}/ Host=${HOST}" >&2
    code="$(http_code "http://${addr}/" -H "Host: ${HOST}")"
    if [[ "${code}" != "000" ]]; then
      echo "  using http://${addr} (HTTP ${code})" >&2
      echo "http://${addr}"
      return
    fi
  fi
  echo "https://${HOST}"
}

curl_json() {
  local method="$1" url="$2" body="${3:-}" token="$4"
  local tmp err code
  tmp="$(mktemp)"
  err="$(mktemp)"
  if [[ -n "${body}" ]]; then
    code="$(curl "${CURL_OPTS[@]}" -o "${tmp}" -w "%{http_code}" -X "${method}" "${url}" \
      -H "Host: ${HOST}" -H "Authorization: Bearer ${token}" \
      -H "Content-Type: application/json" -d "${body}" 2>"${err}")" || true
  else
    code="$(curl "${CURL_OPTS[@]}" -o "${tmp}" -w "%{http_code}" -X "${method}" "${url}" \
      -H "Host: ${HOST}" -H "Authorization: Bearer ${token}" \
      -H "Content-Type: application/json" 2>"${err}")" || true
  fi
  if [[ -s "${err}" ]]; then
    echo "  curl: $(tr '\n' ' ' < "${err}")" >&2
  fi
  rm -f "${err}"
  echo "${code}" "${tmp}"
}

fail=0
OC_TOKEN="$(oc whoami -t)"
echo "== MaaS host =="
echo "  ${HOST}"
echo "  user: $(oc whoami)"
BASE_URL="$(select_base_url)"
MAAS_API="${BASE_URL}/maas-api"
echo "  base: ${BASE_URL}"

if [[ -z "${MAAS_API_KEY:-}" ]]; then
  echo "== Mint API key =="
  mint_body="$(python3 -c 'import json,sys; print(json.dumps({
    "name": sys.argv[1], "description": "Generated by probe-maas.sh",
    "subscription": sys.argv[2], "ephemeral": True, "expiresIn": "1h",
  }))' "${KEY_NAME}" "${SUBSCRIPTION}")"
  read -r mint_code mint_file < <(curl_json POST "${MAAS_API}/v1/api-keys" "${mint_body}" "${OC_TOKEN}")
  mint_body_out="$(cat "${mint_file}")"
  rm -f "${mint_file}"
  echo "  HTTP ${mint_code}"
  echo "${mint_body_out}" | python3 -m json.tool 2>/dev/null || echo "${mint_body_out}"
  if [[ "${mint_code}" != "200" && "${mint_code}" != "201" ]]; then
    echo "FAIL minting API key (HTTP ${mint_code})" >&2
    exit 1
  fi
  MAAS_API_KEY="$(echo "${mint_body_out}" | json_field key)"
  [[ -n "${MAAS_API_KEY}" && "${MAAS_API_KEY}" != "null" ]] || { echo "FAIL no .key" >&2; exit 1; }
  echo "  export MAAS_API_KEY='${MAAS_API_KEY}'"
fi

echo "== GET /v1/models =="
read -r models_code models_file < <(curl_json GET "${BASE_URL}/v1/models" "" "${MAAS_API_KEY}")
cat "${models_file}"; rm -f "${models_file}"
[[ "${models_code}" == "200" ]] || fail=1

echo "== POST /v1/chat/completions =="
chat_body="$(python3 -c 'import json,sys; print(json.dumps({
    "model": sys.argv[1],
    "messages": [{"role": "user", "content": sys.argv[2]}],
    "max_tokens": int(sys.argv[3]),
}))' "${MODEL}" "${PROMPT}" "${MAX_TOKENS}")"
read -r chat_code chat_file < <(curl_json POST "${BASE_URL}/v1/chat/completions" "${chat_body}" "${MAAS_API_KEY}")
cat "${chat_file}"; rm -f "${chat_file}"
[[ "${chat_code}" == "200" ]] || fail=1
exit "${fail}"
